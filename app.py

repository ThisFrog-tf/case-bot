from flask import Flask
import os
import threading
import subprocess

app = Flask('')

@app.route('/')
def home():
    return "I'm alive!"

def run_web():
    port = int(os.environ.get('PORT', 8080))
    app.run(host='0.0.0.0', port=port)

threading.Thread(target=run_web).start()
subprocess.run(['python', 'bot.py'])
